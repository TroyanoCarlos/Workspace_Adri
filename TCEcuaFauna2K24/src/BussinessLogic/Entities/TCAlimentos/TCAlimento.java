package BussinessLogic.Entities.TCAlimentos;

public abstract class TCAlimento {
    private String tcTipoAlimento;
    private String tcNombre;

    
    public String getTcTipoAlimento() {
        return tcTipoAlimento;
    }
    public void setTcTipoAlimento(String tcTipoAlimento) {
        this.tcTipoAlimento = tcTipoAlimento;
    }
    public String getTcNombre() {
        return tcNombre;
    }
    public void setTcNombre(String tcNombre) {
        this.tcNombre = tcNombre;
    }
    

  
}
